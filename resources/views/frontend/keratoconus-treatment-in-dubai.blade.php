                <h2 class="mb-2">Keratoconus Treatment in Dubai: Our Treatment Options</h2>
                <p style="text-align: justify;">
                    Treatment depends on how advanced the condition is and how your child's cornea is responding over time. Here's the full range of options, from the earliest stage onward.
                </p>

                <h3 class="mb-2">Eyeglasses and Soft Contact Lenses</h3>
                <p style="text-align: justify;">
                    In the earliest stages, standard eyeglasses or soft contact lenses can often correct vision effectively. This is usually paired with close monitoring to catch any early signs of progression.
                </p>

                <h3 class="mb-2">Rigid Gas-Permeable (RGP) Lenses</h3>
                <p style="text-align: justify;">
                    As the cornea becomes more irregular, RGP lenses help correct distortion that soft lenses or glasses can no longer manage by creating a smooth, regular refracting surface over the irregular cornea.
                </p>

                <h3 class="mb-2">Hybrid Lenses</h3>
                <p style="text-align: justify;">
                    For children who find rigid lenses uncomfortable, hybrid lenses combine a rigid center with a soft outer skirt, offering the visual clarity of RGP lenses with noticeably better day-to-day comfort.
                </p>

                <h3 class="mb-2">Corneal Cross-Linking (CXL)</h3>
                <p style="text-align: justify;">
                    This is the core treatment for progressive keratoconus, and it's the only procedure clinically proven to stop the disease from advancing further. Riboflavin (vitamin B2) drops are applied to the cornea, followed by a controlled dose of UV-A light. The reaction strengthens the collagen bonds holding the cornea's shape, stiffening the tissue and halting further bulging. For children caught early, this single procedure can preserve vision for the long run and, in many cases, help avoid the need for more invasive treatment later.
                </p>

                <h3 class="mb-2">Intracorneal Ring Segments (Intacs)</h3>
                <p style="text-align: justify;">
                    For select cases where contact lenses aren't well tolerated, and the cornea is still relatively clear, small ring segments can be inserted to reshape the cornea and improve its regularity, often improving both comfort and vision.
                </p>

                <h3 class="mb-2">Corneal Transplant (DALK or PK)</h3>
                <p style="text-align: justify;">
                    Reserved for advanced cases with significant scarring, ranging from partial-thickness grafts (DALK) to full-thickness transplants (PK). Thanks to earlier diagnosis and the widespread use of cross-linking, the need for transplants in children has become far less common than it once was.
                </p>

                <h3 class="mb-2">Ongoing Follow-Up</h3>
                <p style="text-align: justify;">
                    Keratoconus isn't treated once and forgotten. Your child will have scheduled reviews with corneal topography to catch any progression early, and the treatment plan will be adjusted as they grow.
